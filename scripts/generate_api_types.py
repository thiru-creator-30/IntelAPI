#!/usr/bin/env python3
"""
Minimal OpenAPI → TypeScript generator for IntelAPI.

Usage:
    python scripts/generate_api_types.py <openapi.json> <output.ts>

Produces a small TS file with interface types for the endpoints actually used by the web app.
The full OpenAPI schema is preserved in a const for runtime reference. This script is intentionally
small; replace with openapi-typescript if a richer typed client is needed later.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path


HEADER = """// AUTO-GENERATED by scripts/generate_api_types.py. Do not edit by hand.
/* eslint-disable @typescript-eslint/no-explicit-any */
"""


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print("usage: generate_api_types.py <openapi.json> <output.ts>", file=sys.stderr)
        return 2
    openapi_path = Path(argv[1])
    out_path = Path(argv[2])
    spec = json.loads(openapi_path.read_text())
    # Extract schemas; emit `interface` declarations for object schemas.
    schemas = (spec.get("components") or {}).get("schemas") or {}
    out: list[str] = [HEADER, "export const OpenAPISchemaSpec = JSON.parse(`" + json.dumps(spec) + "`);", ""]
    for name, schema in schemas.items():
        if schema.get("type") == "object" or "properties" in schema:
            out.append(f"export interface {name} {{")
            for pname, p in (schema.get("properties") or {}).items():
                req = pname in (schema.get("required") or [])
                ts_type = _ts_type(p)
                q = "?" if not req else ""
                out.append(f"  {pname}{q}: {ts_type};")
            out.append("}\n")
    out_path.write_text("\n".join(out))
    return 0


def _ts_type(schema: dict) -> str:
    t = schema.get("type")
    if t == "string":
        return "string"
    if t in {"integer", "number"}:
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "array":
        items = schema.get("items") or {}
        return f"Array<{_ts_type(items)}>"
    if t == "object" or "properties" in schema:
        return "{ [k: string]: any }"
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if schema.get("nullable"):
        return "any | null"
    return "any"


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
